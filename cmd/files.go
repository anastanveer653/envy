func newImportCmd(a *app) *cobra.Command {
	var skipExisting bool
	cmd := &cobra.Command{
		Use:   "import [FILE]",
		Short: "Import secrets from a .env file",
		Long: `Read KEY=value pairs from a .env file (default ".env") into the selected
environment. Every key is validated before anything is written.`,
		Example: `  envy import
  envy import .env.production -e production
  envy import .env.local --skip-existing`,
		Args: cobra.MaximumNArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			file := ".env"
			if len(args) == 1 {
				file = args[0]
			}
			env, err := a.targetEnv()
			if err != nil {
				return err
			}
			f, err := os.Open(file)
			if err != nil {
				return err
			}
			vars, err := dotenv.Parse(f)
			f.Close()
			if err != nil {
				return fmt.Errorf("parse %s: %w", file, err)
			}
			keys := make([]string, 0, len(vars))
			for k := range vars {
				if err := store.ValidateKey(k); err != nil {
					return fmt.Errorf("%s: %w", file, err)
				}
				keys = append(keys, k)
			}
			sort.Strings(keys)

			s, err := a.unlock()
			if err != nil {
				return err
			}
			if err := requireEnv(s, env); err != nil {
				return err
			}

			var added, updated, skipped int
			for _, k := range keys {
				if _, err := s.Get(env, k); err == nil && skipExisting {
					skipped++
					continue
				}
				wasThere, err := s.Set(env, k, vars[k], "")
				if err != nil {
					return err
				}
				if wasThere {
					updated++
				} else {
					added++
				}
			}
			if err := s.Save(); err != nil {
				return err
			}
			ui.Success(a.stderr, "Imported %s into %s: %d added, %d updated, %d skipped",
				file, ui.Bold(env), added, updated, skipped)
			return nil
		},
	}
	cmd.Flags().BoolVar(&skipExisting, "skip-existing", false, "keep values already in the store")
	return cmd
}

func newExportCmd(a *app) *cobra.Command {
	var output string
	var force, template bool
	cmd := &cobra.Command{
		Use:   "export",
		Short: "Write an environment as a .env file",
		Long: `Print the selected environment in .env format, or write it to a file with
--output. Prefer 'envy run' where you can: it never writes secrets to disk.

--template writes keys without values, which keeps .env.example in sync.`,
		Example: `  envy export -e staging > .env
  envy export -e production -o .env.production
  envy export --template -o .env.example --force`,
		Args: cobra.NoArgs,
		RunE: func(cmd *cobra.Command, args []string) error {
			env, err := a.targetEnv()
			if err != nil {
				return err
			}
			s, err := a.unlock()
			if err != nil {
				return err
			}
			if err := requireEnv(s, env); err != nil {
				return err
			}
			secrets, _ := s.Secrets(env)
			keys, _ := s.Keys(env)

			entries := make([]dotenv.Entry, 0, len(keys))
			for _, k := range keys {
				e := dotenv.Entry{Key: k, Comment: secrets[k].Note}
				if !template {
					e.Value = secrets[k].Value
				}
				entries = append(entries, e)
			}
			header := []string{"Generated by envy from the " + env + " environment. Do not commit."}
			if template {
				header = []string{"Template generated by envy from the " + env + " environment.", "Fill in values locally; this file is safe to commit."}
			}

			var buf bytes.Buffer
			if err := dotenv.Write(&buf, header, entries); err != nil {
				return err
			}
			if output == "" || output == "-" {
				_, err := a.stdout.Write(buf.Bytes())
				return err
			}

			flags := os.O_WRONLY | os.O_CREATE | os.O_TRUNC
			if !force {
				flags |= os.O_EXCL
			}
			f, err := os.OpenFile(output, flags, 0o600)
			if errors.Is(err, os.ErrExist) {
				return fmt.Errorf("%s already exists; pass --force to overwrite", output)
			}
			if err != nil {
				return err
			}
			if _, err := f.Write(buf.Bytes()); err != nil {
				f.Close()
				return err
			}
			if err := f.Close(); err != nil {
				return err
			}
			ui.Success(a.stderr, "Wrote %s to %s", plural(len(entries), "key"), output)
			if !template && !gitIgnores(output) {
				ui.Warn(a.stderr, "%s is not ignored by git. Add it to .gitignore before committing.", output)
			}
			return nil
		},
	}
	cmd.Flags().StringVarP(&output, "output", "o", "", "write to FILE instead of stdout")
	cmd.Flags().BoolVarP(&force, "force", "f", false, "overwrite FILE if it exists")
	cmd.Flags().BoolVar(&template, "template", false, "write keys and notes only, without values")
	return cmd
}

// gitIgnores reports whether git would ignore path. Outside a repository it
// returns true, since there is nothing to warn about.
func gitIgnores(path string) bool {
	if _, err := exec.LookPath("git"); err != nil {
		return true
	}
	cmd := exec.Command("git", "check-ignore", "-q", "--", filepath.Base(path))
	cmd.Dir = filepath.Dir(path)
	err := cmd.Run()
	var ee *exec.ExitError
	if errors.As(err, &ee) {
		// 1 means "not ignored"; 128 means not a repository.
		return ee.ExitCode() != 1
	}
	return err == nil
}
